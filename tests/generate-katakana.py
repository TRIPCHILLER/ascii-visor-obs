"""Reproducible pixel atlas from the unmodified, bundled PixelMplus12 Bold."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
path = root/'data/fonts/PixelMplus12-Bold.ttf'
expected = '7276753dc80861e2f45257b7b1a54c967c160065f5d40e10fb48aabd5648a2a6'
assert hashlib.sha256(path.read_bytes()).hexdigest() == expected
font = ImageFont.truetype(str(path), 12)
cmap = TTFont(path).getBestCmap()
glyphs = []
for code in [0x3000, 0x3001, 0x3002, *range(0x30A1, 0x30FB)]:
    if code not in cmap:
        continue
    ch = chr(code)
    image = Image.new('L', (12,12))
    ImageDraw.Draw(image).text((0,0), ch, font=font, fill=255, stroke_width=0)
    image = image.point(lambda p: 255 if p>=128 else 0)
    area = sum(image.tobytes())//255
    glyphs.append((area, code, image))
glyphs.sort(key=lambda item: (item[0],item[1]))
levels = [glyphs[0]]
for i in range(1,10):
    target = glyphs[-1][0] * i/9
    candidates = [g for g in glyphs if g[0] > levels[-1][0]]
    levels.append(min(candidates, key=lambda item: (abs(item[0]-target), item[1])))
assert levels[0][0] == 0 and len(set(g[0] for g in levels))==10
lines = ['/* Generated by tests/generate-katakana.py from PixelMplus12 Bold.',
         ' * Copyright (C) 2013 itouhiro; Copyright (C) 2002-2013 M+ FONTS PROJECT.',
         ' * M+ FONT LICENSE: unlimited use/copy/distribution with or without modification.',
         ' * See data/fonts/PixelMplus-LICENSE.txt and PixelMplus-README.md.',
         ' * Font SHA256: '+expected+' */',
         '#define VISOR_KANA_SIZE 12', '#define VISOR_KANA_COUNT 10',
         'static const unsigned char visor_kana_pixels[10][144] = {']
for area, code, image in levels:
    lines.append(' /* U+%04X %s; %d filled pixels */' % (code,chr(code),area))
    lines.append(' {'+','.join(str(p//255) for p in image.tobytes())+'},')
lines.append('};\n')
(root/'src/katakana-pixel.h').write_text('\n'.join(lines), encoding='utf-8')
qa = root/'build/qa';qa.mkdir(parents=True,exist_ok=True)
board = Image.new('RGB',(1080,170),'#0a1014');draw=ImageDraw.Draw(board)
label=ImageFont.truetype('C:/Windows/Fonts/consola.ttf',18)
draw.text((12,8),'KATAKANA / PixelMplus12 Bold / actual bundled glyphs',font=label,fill='#9fd8f5')
for i,(area,code,image) in enumerate(levels):
    tile=image.convert('RGB').resize((72,72),Image.Resampling.NEAREST)
    board.paste(tile,(12+i*106,45));draw.text((12+i*106,125),f'{i}: {area}',font=label,fill='white')
board.save(qa/'KATAKANA_GLYPHS.png')
(qa/'katakana-glyphs.json').write_text(json.dumps([{'code':hex(c),'area':a} for a,c,_ in levels],indent=2),encoding='utf-8')
print('PixelMplus12 Bold:',[(hex(c),a) for a,c,_ in levels])
