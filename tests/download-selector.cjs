const assert=require('node:assert/strict');
const {selectInstaller,matches}=require('../docs/download/selector.js');
const base='https://github.com/TRIPCHILLER/ascii-visor-obs/';
const file=(name,changes={})=>({name,state:'uploaded',size:123,browser_download_url:base+'releases/download/v1/'+name,...changes});
const release=(id,date,assets,changes={})=>({id,published_at:date,html_url:base+'releases/tag/v'+id,tag_name:'v'+id,draft:false,prerelease:false,assets,...changes});
const windows=file('ASCII-VISOR-0.3.1-rc1-Windows-x64-Setup.exe');
const linux=file('ASCII-VISOR-0.3.1-rc1-Linux-x86_64-Setup.AppImage');
const mac=file('ASCII-VISOR-0.3.1-rc1-macOS-universal-Setup.zip');
const old=release(1,'2026-01-01',[file('ASCII-VISOR-0.2.8-Setup.exe')]);
const candidate=release(2,'2026-02-01',[windows,linux,mac],{prerelease:true});
const draft=release(3,'2026-03-01',[windows],{draft:true});
assert.equal(selectInstaller([old,candidate,draft],'windows').release.id,2);
assert.equal(selectInstaller([old,candidate,draft],'linux').release.id,2);
assert.equal(selectInstaller([old,candidate,draft],'macos').release.id,2);
const partial=release(4,'2026-04-01',[windows]);
assert.equal(selectInstaller([candidate,partial],'linux').release.id,2);
assert.equal(selectInstaller([candidate,partial],'windows').release.id,4);
assert.equal(selectInstaller([old],'windows').release.id,1);
assert.equal(selectInstaller([old],'macos'),null);
assert.equal(selectInstaller([release(9,'2026-05-01',[file(windows.name,{state:'new'})])],'windows'),null);
assert.equal(selectInstaller([release(9,'2026-05-01',[file(windows.name,{browser_download_url:'https://example.com/x'})])],'windows'),null);
assert.equal(selectInstaller([release(9,'2026-05-01',[windows],{html_url:'https://example.com/'})],'windows'),null);
assert.equal(matches('ASCII-VISOR-0.3.1-rc1-Windows-x64-Plugin.zip','windows'),false);
assert.equal(matches('ASCII-VISOR-0.3.1-rc1-Linux-x86_64-Setup.tar.gz','linux'),false);
assert.equal(matches('ASCII-VISOR-Windows-x64-Setup.exe','windows'),true);
assert.equal(matches('ASCII-VISOR-1.0.0-Linux-x86_64-Setup.AppImage','linux'),true);
assert.equal(selectInstaller([candidate],'other'),null);
console.log('PASS: permanent download selection, draft exclusion, per-platform fallback, pre-release label, legacy Windows and repository URL validation');
